/** 与 app.js 的初聊档保持一致：性能样本要量的是最短路径，不是复杂场景。 */
const PERF_UI_VALUES = Object.freeze({ mode: "anti", stage: "初聊", styleBias: "mix", goal: "把这一句自然接下去" });

export function toMessages(lines) {
  return lines.map((line, index) => {
    const isHer = line.startsWith("她：");
    return {
      mid: `p-mid-${index}`,
      type: isHer ? "her" : "me",
      who: isHer ? "她" : "我",
      text: line.replace(/^(她|我)：/, ""),
      source: isHer ? "model" : "user"
    };
  });
}

/** 每个样本的出站消息构造，交给探针在浏览器里逐条执行。 */
export function buildPerfCaseMessages(persona, item) {
  return buildHerMessages(persona, {}, toMessages(item.lines), PERF_UI_VALUES);
}
