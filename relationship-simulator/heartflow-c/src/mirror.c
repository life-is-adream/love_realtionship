static const HfLayer *lookup(const char *w)
{
    int i;
    if (!w || !*w) return NULL;
    for (i = 0; LAYERS[i].surface; i++)
        if (strcmp(LAYERS[i].surface, w) == 0) return &LAYERS[i];
    return NULL;
}

void hf_mirror(const char *text, const HfAffect *a, FILE *out)
{
    const HfLayer *L;

    (void)text;
    fprintf(out, "\n【1 · 你在说的】\n");

    if (a->hits == 0) {
        fprintf(out, "  这段话里我没抓到明确的情绪词。\n");
        fprintf(out, "  说不清本身也是一种状态——可以先只描述「发生了什么」，\n");
        fprintf(out, "  不评价对错，往往比硬找一个词更接近真实。\n");
        return;
    }

    fprintf(out, "  字面上     %s（强度 %d/100）\n", a->primary, a->intensity);
    fprintf(out, "  依据       %s\n", a->evidence);

    L = lookup(a->primary);
    if (!L && a->secondary[0]) L = lookup(a->secondary);

    if (L) {
        fprintf(out, "  更底下     %s\n", L->under);
        fprintf(out, "  为什么这么读：%s。\n", L->why);
    }

    if (a->intensity >= 80)
        fprintf(out, "  这个强度已经不适合在今晚做任何决定。\n");

    fprintf(out, "\n  这是一句可以自己补完的话，不是我要替你写：\n");
    fprintf(out, "      \"我不是______，我是______。\"\n");
    if (L)
        fprintf(out, "      例：我不是在生你的气，我是%s。\n", L->under);
    else
        fprintf(out, "      例：我不是想吵赢，我是想被认真对待一次。\n");
    fprintf(out, "  补得出来，说明你想清楚了；补不出来，说明还差一层。\n");
}
