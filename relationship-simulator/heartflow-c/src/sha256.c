static uint32_t rotr(uint32_t x, int n) { return (x >> n) | (x << (32 - n)); }

static void block(HfSha256 *s, const uint8_t *p)
{
    uint32_t w[64], a, b, c, d, e, f, g, h;
    int i;

    for (i = 0; i < 16; i++) {
        w[i] = ((uint32_t)p[i * 4] << 24) | ((uint32_t)p[i * 4 + 1] << 16) |
               ((uint32_t)p[i * 4 + 2] << 8) | (uint32_t)p[i * 4 + 3];
    }
    for (i = 16; i < 64; i++) {
        uint32_t s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }

    a = s->h[0]; b = s->h[1]; c = s->h[2]; d = s->h[3];
    e = s->h[4]; f = s->h[5]; g = s->h[6]; h = s->h[7];

    for (i = 0; i < 64; i++) {
        uint32_t S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
        uint32_t ch = (e & f) ^ ((~e) & g);
        uint32_t t1 = h + S1 + ch + K[i] + w[i];
        uint32_t S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
        uint32_t mj = (a & b) ^ (a & c) ^ (b & c);
        uint32_t t2 = S0 + mj;
        h = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }

    s->h[0] += a; s->h[1] += b; s->h[2] += c; s->h[3] += d;
    s->h[4] += e; s->h[5] += f; s->h[6] += g; s->h[7] += h;
}

void hf_sha256_init(HfSha256 *s)
{
    s->h[0] = 0x6a09e667u; s->h[1] = 0xbb67ae85u;
    s->h[2] = 0x3c6ef372u; s->h[3] = 0xa54ff53au;
    s->h[4] = 0x510e527fu; s->h[5] = 0x9b05688cu;
    s->h[6] = 0x1f83d9abu; s->h[7] = 0x5be0cd19u;
    s->bits = 0;
    s->used = 0;
}

void hf_sha256_update(HfSha256 *s, const void *data, size_t len)
{
    const uint8_t *p = (const uint8_t *)data;
    s->bits += (uint64_t)len * 8;

    if (s->used) {
        size_t take = 64 - s->used;
        if (take > len) take = len;
        memcpy(s->buf + s->used, p, take);
        s->used += take;
        p += take;
        len -= take;
        if (s->used == 64) {
            block(s, s->buf);
            s->used = 0;
        }
    }
    while (len >= 64) {
        block(s, p);
        p += 64;
        len -= 64;
    }
    if (len) {
        memcpy(s->buf, p, len);
        s->used = len;
    }
}

void hf_sha256_final(HfSha256 *s, uint8_t out[32])
{
    uint64_t bits = s->bits;
    uint8_t pad[72];
    size_t padlen;
    int i;

    memset(pad, 0, sizeof pad);
    pad[0] = 0x80;
    padlen = (s->used < 56) ? (56 - s->used) : (120 - s->used);
    hf_sha256_update(s, pad, padlen);

    for (i = 0; i < 8; i++) pad[i] = (uint8_t)(bits >> (56 - 8 * i));
    hf_sha256_update(s, pad, 8);

    for (i = 0; i < 8; i++) {
        out[i * 4]     = (uint8_t)(s->h[i] >> 24);
        out[i * 4 + 1] = (uint8_t)(s->h[i] >> 16);
        out[i * 4 + 2] = (uint8_t)(s->h[i] >> 8);
        out[i * 4 + 3] = (uint8_t)(s->h[i]);
    }
}

void hf_sha256_hex(const void *data, size_t len, char out[65])
{
    HfSha256 s;
    uint8_t d[32];
    static const char *hex = "0123456789abcdef";
    int i;

    hf_sha256_init(&s);
    hf_sha256_update(&s, data, len);
    hf_sha256_final(&s, d);
    for (i = 0; i < 32; i++) {
        out[i * 2] = hex[d[i] >> 4];
        out[i * 2 + 1] = hex[d[i] & 15];
    }
    out[64] = '\0';
}
