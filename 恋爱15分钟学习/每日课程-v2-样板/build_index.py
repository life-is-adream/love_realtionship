def parse_lessons():
    pat = re.compile(r"^(\d{4}-\d{2}-\d{2})-第(\d+)课-(.+)\.md$")
    rows = []
    for p in sorted(LESSON_DIR.glob("*.md")):
        m = pat.match(p.name)
        if not m:
            continue
        date, lid, title = m.group(1), int(m.group(2)), m.group(3)
        module, layer, concepts = TAGS[lid]
        season = "S1" if int(module) <= 11 else ("S2" if int(module) <= 16 else "S3")
        rows.append({
            "id": lid,
            "date": date,
            "title": title,
            "file": f"每日课程/{p.name}",
            "season": season,
            "module": int(module),
            "module_name": MODULES[module],
            "layer": layer,
            "concepts": concepts.split("|"),
            "review_week": (lid - 1) // 6 + 1,
            "status": "keep",
        })
    rows.sort(key=lambda r: r["id"])
    return rows


